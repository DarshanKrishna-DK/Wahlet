import assert from 'node:assert/strict';
import { mkdtempSync, mkdirSync, readFileSync } from 'node:fs';
import { join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { createHash } from 'node:crypto';
import { execFileSync } from 'node:child_process';

const root = fileURLToPath(new URL('../', import.meta.url));
const version = JSON.parse(readFileSync(join(root, 'package.json'), 'utf8')).version;
const archive = resolve(process.argv[2] ?? join(root, `.local/releases/wahlet-${version}.tgz`));
const manifest = JSON.parse(readFileSync(`${archive}.manifest.json`, 'utf8'));
assert.equal(createHash('sha256').update(readFileSync(archive)).digest('hex'), manifest.sha256, 'Archive checksum mismatch');
assert(manifest.files.some(file => file.path === 'dist/cli/index.js'));
assert(manifest.files.some(file => file.path === 'apps/web/dist/index.html'));
assert(manifest.files.every(file => !/(?:^|\/)(?:docs|\.agents|\.codex|\.local|\.env|src|checks|node_modules)(?:\/|$)/.test(file.path)), 'Private or development files in release');
if (!process.env.npm_execpath) throw new Error('Run with npm run check:release.');
mkdirSync(join(root, '.local/release-checks'), { recursive: true });
const workspace = mkdtempSync(join(root, '.local/release-checks/install-'));
execFileSync(process.execPath, [process.env.npm_execpath, 'install', '--prefix', workspace, '--ignore-scripts', '--omit=dev', '--no-audit', '--no-fund', archive], { cwd: workspace, stdio: 'pipe', windowsHide: true });
const entry = join(workspace, 'node_modules/wahlet/dist/cli/index.js');
const env = { ...process.env, WAHLET_STATE_DIR: join(workspace, 'wallet-state') };
const run = args => execFileSync(process.execPath, [entry, ...args], { cwd: workspace, env, encoding: 'utf8', windowsHide: true });
assert.equal(run(['--version']).trim(), version);
const status = JSON.parse(run(['doctor', '--offline']));
assert.equal(status.ready, true);
assert.equal(status.checks.find(check => check.name === 'state').detail, env.WAHLET_STATE_DIR);
const config = JSON.parse(run(['config', 'claude']));
assert.equal(config.mcpServers.wahlet.command, process.execPath);
assert.deepEqual(config.mcpServers.wahlet.args, [entry, 'mcp']);
assert.equal(config.mcpServers.wahlet.env.WAHLET_STATE_DIR, env.WAHLET_STATE_DIR);
assert(run(['config', 'codex']).includes('[mcp_servers.wahlet.env]'));
assert(run(['config', 'chatgpt']).includes('https://developers.openai.com/api/docs/guides/secure-mcp-tunnels'));
process.stdout.write(`Verified checksum, public manifest, fresh dependency installation, CLI, console assets, isolated state, and client configuration for ${version}.\n`);
